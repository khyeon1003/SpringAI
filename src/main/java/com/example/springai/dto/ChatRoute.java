package com.example.springai.dto;

/**
 * 요청이 어느 경로로 처리되었는지 나타낸다.
 *
 * <p>응답만 보고 "무엇을 근거로 답했는가"를 판별할 수 있어야 검증이 가능하다.
 * {@code contexts} 만으로는 개인 학적 정보를 도구로 가져왔는지 알 수 없어 별도로 둔다.
 */
public enum ChatRoute {

    /** 가드레일이 차단했다. 검색도 도구 호출도 일어나지 않았다. */
    BLOCK,

    /** 검색된 학칙 문서만 근거로 답했다. */
    RAG_ONLY,

    /** 학칙 문서와 개인 학적 정보를 함께 근거로 삼았다. */
    RAG_WITH_TOOL,

    /** 도구로 가져온 개인 학적 정보만 근거로 삼았다. 문서 근거는 없다. */
    TOOL_ONLY,

    /** 차단하지는 않았으나 근거가 없다. 문서에 없는 학사 질문이 여기에 해당한다. */
    NO_EVIDENCE
}
